-- 2. ATOMIC PAYMENT VERIFICATION FUNCTION
-- ============================================================
CREATE OR REPLACE FUNCTION verify_payment_and_order(
  p_payment_id UUID,
  p_transaction_id TEXT,
  p_network TEXT,
  p_currency TEXT,
  p_amount_units NUMERIC,
  p_confirmations INTEGER,
  p_block_number TEXT,
  p_token_address TEXT,
  p_recipient_address TEXT
) RETURNS payments
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_payment payments;
  v_order orders;
BEGIN
  SELECT * INTO v_payment FROM payments WHERE id = p_payment_id FOR UPDATE;
  IF NOT FOUND OR v_payment.status <> 'submitted' OR v_payment.transaction_id <> p_transaction_id THEN
    RAISE EXCEPTION 'payment is not awaiting verification';
  END IF;
  SELECT * INTO v_order FROM orders WHERE id = v_payment.order_id FOR UPDATE;
  IF NOT FOUND OR v_order.payment_status <> 'submitted' THEN
    RAISE EXCEPTION 'order is not awaiting payment verification';
  END IF;
  IF EXISTS (SELECT 1 FROM payments WHERE transaction_id = p_transaction_id AND id <> p_payment_id) THEN
    RAISE EXCEPTION 'transaction has already been used';
  END IF;
  UPDATE payments SET status = 'verified', verified_at = now(), updated_at = now(),
    network = p_network, currency = p_currency,
    verification_reason = jsonb_build_object('amount_units', p_amount_units, 'confirmations', p_confirmations, 'block_number', p_block_number, 'token_address', lower(p_token_address), 'recipient_address', lower(p_recipient_address))::text
    WHERE id = p_payment_id RETURNING * INTO v_payment;
  UPDATE orders SET payment_status = 'verified', txid = p_transaction_id, updated_at = now()
    WHERE id = v_order.id AND payment_status = 'submitted';
  IF NOT FOUND THEN RAISE EXCEPTION 'order verification race'; END IF;
  RETURN v_payment;
END;
$$;
REVOKE EXECUTE ON FUNCTION verify_payment_and_order(UUID, TEXT, TEXT, TEXT, NUMERIC, INTEGER, TEXT, TEXT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION verify_payment_and_order(UUID, TEXT, TEXT, TEXT, NUMERIC, INTEGER, TEXT, TEXT, TEXT) TO service_role;

