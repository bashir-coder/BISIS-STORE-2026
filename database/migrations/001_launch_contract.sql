-- Supabase Auth identity synchronization
CREATE OR REPLACE FUNCTION public.handle_supabase_auth_user()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_provider TEXT;
BEGIN
  -- Normalize auth_provider to 'google' or 'email' to comply with users_auth_provider_check
  IF COALESCE(NEW.raw_app_meta_data ->> 'provider', NEW.app_metadata ->> 'provider', '') = 'google' THEN
    v_provider := 'google';
  ELSE
    v_provider := 'email';
  END IF;

  INSERT INTO public.users (id, email, name, full_name, avatar, auth_provider, role, is_verified, is_active)
  SELECT NEW.id,
         NEW.email,
         COALESCE(NEW.raw_user_meta_data ->> 'full_name', NEW.raw_user_meta_data ->> 'name', NEW.email),
         COALESCE(NEW.raw_user_meta_data ->> 'full_name', NEW.raw_user_meta_data ->> 'name', NEW.email),
         COALESCE(NEW.raw_user_meta_data ->> 'avatar_url', NEW.raw_user_meta_data ->> 'picture'),
         v_provider,
         'client',
         NEW.email_confirmed_at IS NOT NULL,
         true
  WHERE NOT EXISTS (SELECT 1 FROM public.users WHERE id = NEW.id OR email = NEW.email);
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE FUNCTION public.handle_supabase_auth_user();

